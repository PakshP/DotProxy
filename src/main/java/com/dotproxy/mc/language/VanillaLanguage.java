package com.dotproxy.mc.language;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.zip.GZIPInputStream;

import static com.dotproxy.Globals.DEFAULT_LOG;

/**
 * Raw vanilla en_us strings and default keybind display names, per Minecraft version.
 *
 * Backed by mcdata/vanilla_lang.json.gz, generated by scripts/gen-vanilla-lang.py straight from Mojang's client jars.
 * Loaded lazily on first use so the proxy's idle footprint is unchanged.
 */
public final class VanillaLanguage {
    private static final String RESOURCE = "/mcdata/vanilla_lang.json.gz";

    /**
     * What a vanilla client of one specific version knows.
     *
     * @param lang     raw en_us translation strings (java format syntax, e.g. "%s was slain by %s")
     * @param keybinds default key mapping name -> display name, e.g. "key.jump" -> "Space"
     */
    public record Snapshot(String versionId, int protocol, Map<String, String> lang, Map<String, String> keybinds) { }

    private record Version(String id, int protocol) { }
    private record Change(int fromIndex, String value) { } // value null = removed

    private record Data(List<Version> versions, Map<String, Object> lang, Map<String, Object> keybinds) { }

    private static volatile Data data;
    private static final Map<Integer, Snapshot> SNAPSHOTS = new ConcurrentHashMap<>();

    private VanillaLanguage() { }

    /**
     * The newest known version whose protocol is <= the given protocol.
     * Protocols older than the oldest generated version resolve to the oldest one.
     */
    public static Snapshot forProtocol(final int protocol) {
        final Data d = data();
        int index = 0;
        for (int i = 0; i < d.versions.size(); i++) {
            if (d.versions.get(i).protocol <= protocol) index = i;
        }
        return SNAPSHOTS.computeIfAbsent(index, VanillaLanguage::buildSnapshot);
    }

    private static Snapshot buildSnapshot(final int index) {
        final Data d = data();
        final Version v = d.versions.get(index);
        return new Snapshot(v.id, v.protocol, resolve(d.lang, index), resolve(d.keybinds, index));
    }

    private static Map<String, String> resolve(final Map<String, Object> history, final int index) {
        final Map<String, String> out = new HashMap<>(history.size() * 4 / 3 + 1);
        for (var entry : history.entrySet()) {
            final Object h = entry.getValue();
            String value;
            if (h instanceof String s) {
                value = s;
            } else {
                value = null;
                for (Change change : (Change[]) h) {
                    if (change.fromIndex > index) break;
                    value = change.value;
                }
            }
            if (value != null) out.put(entry.getKey(), value);
        }
        return Map.copyOf(out);
    }

    private static Data data() {
        Data d = data;
        if (d == null) {
            synchronized (VanillaLanguage.class) {
                d = data;
                if (d == null) {
                    data = d = load();
                }
            }
        }
        return d;
    }

    private static Data load() {
        final var stream = VanillaLanguage.class.getResourceAsStream(RESOURCE);
        if (stream == null) throw new IllegalStateException("Missing resource " + RESOURCE);
        try (var reader = new InputStreamReader(new GZIPInputStream(stream), StandardCharsets.UTF_8)) {
            final JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
            final List<Version> versions = new ArrayList<>();
            for (JsonElement e : root.getAsJsonArray("versions")) {
                final JsonObject o = e.getAsJsonObject();
                versions.add(new Version(o.get("id").getAsString(), o.get("protocol").getAsInt()));
            }
            final var result = new Data(
                List.copyOf(versions),
                readHistory(root.getAsJsonObject("lang")),
                readHistory(root.getAsJsonObject("keybinds")));
            DEFAULT_LOG.debug("Loaded vanilla language data for {} versions ({} keys)", versions.size(), result.lang.size());
            return result;
        } catch (final Exception e) {
            throw new IllegalStateException("Failed loading " + RESOURCE, e);
        }
    }

    private static Map<String, Object> readHistory(final JsonObject obj) {
        final Map<String, Object> out = new HashMap<>(obj.size() * 4 / 3 + 1);
        for (var entry : obj.entrySet()) {
            final JsonElement v = entry.getValue();
            if (v.isJsonPrimitive()) {
                out.put(entry.getKey(), v.getAsString());
            } else {
                final JsonArray arr = v.getAsJsonArray();
                final Change[] changes = new Change[arr.size()];
                for (int i = 0; i < arr.size(); i++) {
                    final JsonArray c = arr.get(i).getAsJsonArray();
                    changes[i] = new Change(c.get(0).getAsInt(), c.get(1).isJsonNull() ? null : c.get(1).getAsString());
                }
                out.put(entry.getKey(), changes);
            }
        }
        return out;
    }
}
